"""Build cards.js, the card database the calculators load.

Usage:
  curl -o cardinfo.json https://db.ygoprodeck.com/api/v7/cardinfo.php
  python3 tools/build_cards.py cardinfo.json cards.js

Each card gets a deck type, a default chance of being set face-down, and
tags guessed from its text (stops attacks, answers summons, removal, ...).
Hand-tuned values in the pages override these guesses for common cards.
"""
import json, re, sys

EXTRA = ("Fusion", "Synchro", "XYZ", "Link")
SKIP = ("Skill Card", "Token")

ATK = re.compile(r"declares an attack|attack declaration|declares a direct attack|negate (the|an|that) attack|end the battle phase|is targeted for an attack|when an opponent's monster attacks")
SUM = re.compile(r"when (your )?opponent (would )?(normal |flip |special |tribute )?summons?|monster(s|\(s\))? (would be |is |are )(normal |flip |special |tribute )?summoned|negate the summon")
REM = re.compile(r"(destroy|banish|return)[^.]{0,60}(spell/trap|spells?/traps?|spell or trap|spell and trap|spells and traps)|(spell/trap|spells?/traps?)[^.]{0,40}; (destroy|banish|return)|target (1|2|up to \d) cards? on the field[^.]{0,30}(destroy|banish)")
MREM = re.compile(r"(destroy|banish|remove from play|return|change)[^.]{0,50}(opponent'?s? (face-up |face-down )?monster|monsters? your opponent controls|monsters? on the field|target 1 monster|all monsters)|take control of|target (1|2|up to \d) cards? on the field[^.]{0,30}(destroy|banish)|(face-up |face-down )?monsters? on the field[^.]{0,30}; (destroy|banish|return)")
NEG = re.compile(r"negate the (activation|summon)")
DRAW = re.compile(r"\bdraw (1|2|3|two|three) cards?\b")
HAND = re.compile(r"from your hand|discard this card|send this card from your hand")
HATK = re.compile(r"attack|battle damage|damage calculation|take damage|would take")

def classify(c):
    t, race, desc = c["type"], c.get("race", ""), c.get("desc", "").lower()
    if t in SKIP: return None
    if "Monster" in t and any(x in t for x in EXTRA): return ("X", 0, "")
    tags = ""
    if "Monster" in t:
        code = "M"
        lvl = c.get("level") or 0
        if "Flip" in t: setw = 100
        elif "cannot be normal summoned" in desc or "must be special summoned" in desc or "must first be special summoned" in desc: setw = 0
        elif "Ritual" in t or lvl >= 7: setw = 2
        elif lvl >= 5: setw = 5
        else: setw = 30
        summon_rule = "cannot be normal summoned" in desc or "must be special summoned" in desc or "must first be special summoned" in desc
        if HAND.search(desc) and HATK.search(desc) and not summon_rule: tags += "h"
    elif t == "Spell Card":
        code, setw = {"Quick-Play": ("Sq", 60), "Continuous": ("Sc", 10), "Equip": ("Sc", 10), "Field": ("Sc", 10)}.get(race, ("Sn", 5))
    elif t == "Trap Card":
        code, setw = "T", 100
    else:
        return None
    responsive = code in ("T", "Sq")
    if responsive and ATK.search(desc): tags += "a"
    if responsive and SUM.search(desc): tags += "s"
    if REM.search(desc): tags += "r"
    if MREM.search(desc): tags += "m"
    if race == "Counter" or NEG.search(desc): tags += "n"
    if DRAW.search(desc): tags += "d"
    return (code, setw, tags)

def main(src, dst):
    cards = json.load(open(src, encoding="utf-8"))["data"]
    seen, lines = set(), []
    for c in sorted(cards, key=lambda c: c["name"]):
        name = c["name"].strip()
        if not name or name in seen or "\t" in name or "\n" in name: continue
        info = classify(c)
        if not info: continue
        seen.add(name)
        ids = sorted({c["id"], *[img["id"] for img in c.get("card_images", [])]})
        code, setw, tags = info
        lines.append("\t".join([name, code, str(setw), tags, ",".join(map(str, ids))]))
    body = json.dumps("\n".join(lines), ensure_ascii=False)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_cards.py from the YGOPRODeck card API. Do not edit by hand.\n")
        f.write("// Fields: name, type (M monster, Sn normal spell, Sq quick-play, Sc continuous/equip/field spell, T trap, X extra deck), set chance %, tags, passcodes\n")
        f.write("window.CARD_DATA = " + body + ";\n")
    print(f"{len(lines)} cards written to {dst}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
